#include <iostream>
#include <algorithm>

using namespace std;

int a[1005][1005];

int main() {
    int r;
    cin >> r;

    // 1. 读入金字塔
    for (int i = 1; i <= r; ++i) {
        for (int j = 1; j <= i; ++j) {
            cin >> a[i][j];
        }
    }

    // 2. 从倒数第二层开始向上“吞并”
    // 每一层的每个数都加上它下面两个邻居中较大的那个
    for (int i = r - 1; i >= 1; --i) {
        for (int j = 1; j <= i; ++j) {
            a[i][j] += max(a[i + 1][j], a[i + 1][j + 1]);
        }
    }

    // 3. 顶端的数字就是全塔精华的最大值
    cout << a[1][1] << endl;

    return 0;
}

/*
【数字金字塔 DP 逻辑拆解】
 
 假设输入的金字塔是这样的（r=3）：
      7
    3   8
  8   1   0

 我们采用“自底向上”的策略，把底层的力量往上“顶”。

 第一步：看最后两层
    3   8
  8   1   0
 对于 3 来说，它脚下是 8 和 1，它选大的(8)，3 变成 3+8 = 11
 对于 8 来说，它脚下是 1 和 0，它选大的(1)，8 变成 8+1 = 9
 
 此时金字塔“缩水”变成了：
      7
   11   9

 第二步：看现在的最后两层
      7
   11   9
 对于 7 来说，它脚下是 11 和 9，它选大的(11)，7 变成 7+11 = 18

 最终答案：18
*/